const { chromium } = require("playwright");
(async () => {
  const exe = "/Users/yatharthsirohi/Library/Caches/ms-playwright/chromium-1217/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing";
  const browser = await chromium.launch({ headless: true, executablePath: exe });
  const context = await browser.newContext({ viewport: {width:1440,height:960}, reducedMotion: "reduce" });
  const page = await context.newPage();
  page.on("pageerror", e => console.log("PAGEERROR", e.message));
  page.on("console", m => { if (m.type()==='error') console.log("CONSOLE", m.text()); });
  await page.goto("http://127.0.0.1:8790/atlas?data=fixtures");
  await page.locator('.atlas-marker[data-id="facility:cern"]').waitFor();
  const box = await page.locator('.atlas-marker[data-id="facility:cern"]').boundingBox();
  console.log("box", box);
  const style = await page.locator('.atlas-marker[data-id="facility:cern"]').evaluate(el => ({opacity: getComputedStyle(el).opacity, display: getComputedStyle(el).display, cls: el.className}));
  console.log("style", style);
  await page.locator('.atlas-marker[data-id="facility:cern"]').evaluate(el => el.click());
  await page.waitForTimeout(1000);
  console.log("hash", await page.evaluate(() => location.hash));
  console.log("detail hidden?", await page.locator("#detail-panel").evaluate(el => el.className));
  console.log("h2 count", await page.locator("#detail-panel h2").count());
  await browser.close();
})();
