const { chromium } = require("playwright");
(async () => {
  const exe = "/Users/yatharthsirohi/Library/Caches/ms-playwright/chromium-1217/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing";
  const browser = await chromium.launch({ headless: true, executablePath: exe });
  const context = await browser.newContext({ viewport: {width:1440,height:960}, reducedMotion: "reduce" });
  const page = await context.newPage();
  page.on("pageerror", e => console.log("PAGEERROR", e.stack || e.message));
  await page.goto("http://127.0.0.1:8790/atlas?data=fixtures");
  await page.locator("#atlas-search").fill("DUNE");
  await page.waitForTimeout(300);
  console.log("results count", await page.locator(".search-result").count());
  const texts = await page.locator(".search-result").allInnerTexts();
  console.log("texts", texts);
  const target = page.locator(".search-result", { hasText: "DUNE — Experiment" });
  console.log("target count", await target.count());
  await target.first().click();
  await page.waitForTimeout(500);
  console.log("hash", await page.evaluate(() => location.hash));
  await browser.close();
})();
