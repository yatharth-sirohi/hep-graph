// about.js — HEP Atlas methodology/coverage page (static/atlas/about.html).
// Reads the same generated bundles the main app does, through loader.js, so
// this page's Coverage numbers can never drift from the data the way a
// hand-typed number in a doc can, and the dev/production fallback behaviour
// (loader.js's resolveBase) is identical to the main app's.

import * as loader from './loader.js';

const statusEl = document.getElementById('coverage-status');
const retryBtn = document.getElementById('coverage-retry');
const entitiesEl = document.getElementById('coverage-entities');
const tiersEl = document.getElementById('coverage-tiers');
const gapsEl = document.getElementById('coverage-gaps');
const versionEl = document.getElementById('about-data-version');

const ENTITY_LABELS = {
  facilities: 'Facilities', sites: 'Sites', accelerators: 'Accelerators',
  beamlines: 'Beamlines', experiments: 'Experiments', detectors: 'Detectors',
  collaborations: 'Collaborations', institutions: 'Institutions', people: 'People',
  results: 'Results', documents: 'Documents', sources: 'Sources', topics: 'Topics',
  memberships: 'Membership rosters',
};
const ENTITY_ORDER = [
  'facilities', 'sites', 'accelerators', 'beamlines', 'experiments', 'detectors',
  'collaborations', 'institutions', 'people', 'results', 'documents', 'sources',
  'topics', 'memberships',
];

function setStatus(text, state) {
  statusEl.textContent = text;
  statusEl.classList.toggle('hidden', !text);
  if (state) statusEl.dataset.state = state; else delete statusEl.dataset.state;
  retryBtn.classList.toggle('hidden', state !== 'error');
}

function renderEntities(manifest) {
  const counts = manifest.counts || {};
  const rows = ENTITY_ORDER
    .filter((key) => counts[key] != null)
    .map((key) => `<tr><th scope="row">${ENTITY_LABELS[key] || key}</th><td class="num">${counts[key]}</td></tr>`)
    .join('');
  entitiesEl.innerHTML = `
    <table class="about-table">
      <caption>From manifest.json's <code>counts</code>, generated by the build (see docs/HEP_ATLAS_COVERAGE.md, "Entities in the atlas")</caption>
      <thead><tr><th scope="col">Type</th><th scope="col" class="num">Count</th></tr></thead>
      <tbody>${rows}</tbody>
    </table>`;
}

function renderTiers(coverage) {
  const buckets = {};
  for (const row of coverage.rows) {
    const tier = row.tier || '?';
    const state = row.researched || 'none';
    if (!buckets[tier]) buckets[tier] = { full: 0, partial: 0, none: 0 };
    buckets[tier][state in buckets[tier] ? state : 'none'] += 1;
  }
  const tiers = Object.keys(buckets).sort();
  const rows = tiers.map((tier) => {
    const b = buckets[tier];
    const total = b.full + b.partial + b.none;
    return `<tr><th scope="row">${tier}</th><td class="num">${total}</td><td class="num">${b.full}</td>`
      + `<td class="num">${b.partial}</td><td class="num">${b.none}</td></tr>`;
  }).join('');
  tiersEl.innerHTML = `
    <table class="about-table">
      <caption>From coverage.json's registry rows, one per experiment (see docs/HEP_ATLAS_COVERAGE.md, "Coverage by tier")</caption>
      <thead><tr>
        <th scope="col">Tier</th><th scope="col" class="num">Rows</th>
        <th scope="col" class="num">Researched: full</th><th scope="col" class="num">Researched: partial</th>
        <th scope="col" class="num">Not researched</th>
      </tr></thead>
      <tbody>${rows}</tbody>
    </table>`;
}

/** `experiment_ids`/`collaboration_ids` rows may be a plain id string or an
 * `{"id", "sources"}` object when the attribution itself needs its own
 * source (A16/A19) — this reads either shape the same way loader.js's own
 * getGraph() does for edges.
 */
function idsFromField(list) {
  return (list || []).map((entry) => (typeof entry === 'string' ? entry : entry && entry.id)).filter(Boolean);
}

function renderGaps(manifest, atlas, resultsBundle, documentsBundle) {
  const experiments = Object.values(atlas.experiments || {});
  const total = experiments.length;

  // Which collaborations have a real, built roster: the same test
  // build_membership_bundles uses (a file under memberships/), read from the
  // manifest's own bundle list rather than guessed or hardcoded, so a
  // future roster added for any collaboration is picked up automatically.
  const rosterSlugs = new Set(
    Object.keys(manifest.bundles || {})
      .filter((key) => key.startsWith('memberships/') && key.endsWith('.json'))
      .map((key) => `collaboration:${key.slice('memberships/'.length, -'.json'.length)}`)
  );

  const experimentsWithResults = new Set();
  for (const result of resultsBundle.list) {
    for (const id of idsFromField(result.experiment_ids)) experimentsWithResults.add(id);
  }
  const experimentsWithDocuments = new Set();
  for (const doc of documentsBundle.list) {
    for (const id of (doc.owner_ids || [])) experimentsWithDocuments.add(id);
  }

  let lackingResults = 0;
  let lackingDocuments = 0;
  let lackingRosters = 0;
  for (const experiment of experiments) {
    if (!experimentsWithResults.has(experiment.id)) lackingResults += 1;
    if (!experimentsWithDocuments.has(experiment.id)) lackingDocuments += 1;
    const collabIds = idsFromField(experiment.collaboration_ids);
    if (!collabIds.some((id) => rosterSlugs.has(id))) lackingRosters += 1;
  }

  const sites = Object.values(atlas.sites || {});
  // A23: a site's coordinates carry `approximate: true` when no fetched
  // source gives the real hall position and the record instead rests on an
  // admitted campus-grade point. loader.js's flattenSiteCoordinates() only
  // adds top-level lat/lon/coord_kind/precision_m — it never removes the
  // original nested `coordinates` object generated bundles carry, so this
  // flag is still readable here.
  const approximateSites = sites.filter((site) => site.coordinates && site.coordinates.approximate === true).length;

  gapsEl.innerHTML = `
    <table class="about-table">
      <caption>Computed live from atlas.json, results.json, documents.json and manifest.json's bundle list (see docs/HEP_ATLAS_COVERAGE.md, "Coverage by category", the "All" row)</caption>
      <tbody>
        <tr><th scope="row">Experiments with no recorded major result</th><td class="num">${lackingResults} of ${total}</td></tr>
        <tr><th scope="row">Experiments with no recorded technical document</th><td class="num">${lackingDocuments} of ${total}</td></tr>
        <tr><th scope="row">Experiments whose collaboration has no built institution roster</th><td class="num">${lackingRosters} of ${total}</td></tr>
        <tr><th scope="row">Sites at campus-grade (approximate) precision</th><td class="num">${approximateSites} of ${sites.length}</td></tr>
      </tbody>
    </table>`;
}

async function main() {
  setStatus('Loading live coverage numbers…');
  const { error } = await loader.init();
  if (error) {
    setStatus(error, 'error');
    return;
  }
  const [manifest, coverage, atlas, resultsBundle, documentsBundle] = await Promise.all([
    loader.getManifest(), loader.getCoverage(), loader.getAtlas(), loader.getResults(), loader.getDocuments(),
  ]);
  renderEntities(manifest);
  renderTiers(coverage);
  renderGaps(manifest, atlas, resultsBundle, documentsBundle);
  versionEl.textContent = `Data version ${manifest.data_version || manifest.version || ''}`
    + ` · built ${manifest.coverage_updated || manifest.build_date || ''}`;
  setStatus('');
}

if (retryBtn) retryBtn.addEventListener('click', () => window.location.reload());

main().catch((error) => {
  window.console.error('HEP Atlas about page failed to load live numbers', error);
  setStatus(`Live coverage numbers could not load: ${error.message}. The rest of this page is still accurate; reload to retry.`, 'error');
});
